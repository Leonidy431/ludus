TITLE = 'Наука. Любовь. Познание.'
RULE = ('The 99 signs-impulses of the Constitution (operator, '
        '2026-10-02); not attributes. The music of each node plays in '
        'the beats listed; at the khachkar the music, like every '
        'machine sound, goes down to -60 dB.')


def build():
    nodes = []
    for node in NODES:
        signs = []
        for n, text in enumerate(node['signs'], 1):
            s = {'n': n, 'text_ru': text}
            key = '%s.%d' % (node['id'], n)
            if key in READINGS:
                s['reading_ru'], s['chorus'] = READINGS[key]
            signs.append(s)
        out = {k: node[k] for k in ('id', 'title_ru', 'sub_ru',
                                    'meaning_ru', 'beats', 'cue')}
        out['signs'] = signs
        nodes.append(out)
    return {'doc': 'docs/HLD_COSMIC_MUSIC_ENTELECHY_2026-10-02.md',
            'title_ru': TITLE, 'rule': RULE, 'silent_beats': ['khachkar'],
            'nodes': nodes}


def check():
    bad = []
    data = build()
    if json.loads(OUT.read_text(encoding='utf-8')) != data:
        bad.append('%s differs from scripts/story/entelechy.py'
                   % OUT.relative_to(ROOT))
    claude = CLAUDE.read_text(encoding='utf-8')
    count = 0
    for node in data['nodes']:
        if len(node['signs']) != 11:
            bad.append('node %s has %d signs' % (node['id'],
                                                 len(node['signs'])))
        for s in node['signs']:
            count += 1
            if s['text_ru'] not in claude:
                bad.append('CLAUDE.md lacks %s.%d' % (node['id'], s['n']))
    if count != 99 or len(data['nodes']) != 9:
        bad.append('not 9 nodes of 99 signs: %d' % count)
    return bad


def main(argv):
    if '--check' in argv:
        bad = check()
        for b in bad:
            print('entelechy:', b)
        print('entelechy: %s' % ('ok' if not bad else 'FAIL'))
        return 1 if bad else 0
    OUT.write_text(json.dumps(build(), ensure_ascii=False, indent=2)
                   + '\n', encoding='utf-8')
    print('wrote', OUT.relative_to(ROOT))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
