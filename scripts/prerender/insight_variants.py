def declination(doy):
    return -23.44 * math.cos(2.0 * math.pi * (doy + 10) / 365.0)


def sun_at(lat, doy, hour):
    """Height and compass bearing (0 north, 90 east) of the sun at a
    solar hour: the declination and hour-angle formula."""
    phi, dec = math.radians(lat), math.radians(declination(doy))
    h = math.radians(15.0 * (hour - 12.0))
    el = math.asin(math.sin(phi) * math.sin(dec)
                   + math.cos(phi) * math.cos(dec) * math.cos(h))
    az = math.atan2(math.sin(h), math.cos(h) * math.sin(phi)
                    - math.tan(dec) * math.cos(phi))
    return math.degrees(el), (math.degrees(az) + 180.0) % 360.0


def rise_set(lat, doy):
    """Solar hours of sunrise and sunset (sun 0.83 degrees under the
    horizon, for refraction and the disc)."""
    phi, dec = math.radians(lat), math.radians(declination(doy))
    c = ((math.sin(math.radians(-0.83)) - math.sin(phi) * math.sin(dec))
         / (math.cos(phi) * math.cos(dec)))
    h0 = math.degrees(math.acos(max(-1.0, min(1.0, c)))) / 15.0
    return 12.0 - h0, 12.0 + h0


def sun_kelvin(el):
    pts = [(0, 2400), (3, 2600), (8, 3100), (15, 4100), (30, 5100),
           (60, 5700), (90, 5800)]
    return interp(pts, el)


def sun_watts(el):
    """Blender sun strength (W/m2): 0 under the horizon, rising fast
    through the first degrees, the scenes' 4-4.5 at a high sun."""
    if el <= 0:
        return 0.0
    return round(4.5 * min(1.0, math.sin(math.radians(el)) * 2.2) ** 0.6,
                 3)


def interp(pts, x):
    if x <= pts[0][0]:
        return pts[0][1]
    for (x0, y0), (x1, y1) in zip(pts, pts[1:]):
        if x <= x1:
            return y0 + (y1 - y0) * (x - x0) / (x1 - x0)
    return pts[-1][1]


def sky(slot, el):
    """The colour and strength of the sky dome at that hour."""
    if slot == 'deep_night':
        return (0.004, 0.006, 0.02), 1.0, True
    if slot == 'moon_night':
        return (0.010, 0.016, 0.040), 1.0, True
    if el < -4:
        return (0.05, 0.09, 0.25), 0.35, False
    if el < 0:
        return (0.30, 0.20, 0.30), 0.35, False
    if el < 8:
        return (0.55, 0.40, 0.32), 0.45, False
    if el < 20:
        return (0.42, 0.52, 0.72), 0.6, False
    return (0.35, 0.50, 0.85), 0.8, False


def hhmm(hour):
    hour %= 24.0
    return '%02d:%02d' % (int(hour), int(round((hour % 1) * 60)) % 60)


def variant(iid, v, slot_i):
    p = PLACES[iid]
    slot, label, mode, off = SLOTS[slot_i]
    rise, sset = rise_set(p['lat'], p['doy'])
    hour = {'rise': rise + off, 'set': sset + off, 'clock': off}[mode]
    el, az = sun_at(p['lat'], p['doy'], hour)
    sky_rgb, sky_strength, starry = sky(slot, el)
    yaw, pitch, dist_k, roll, lens_k = CAMS[slot_i]
    span = p['span']
    lens = max(18.0, min(135.0, round(p['lens'] * lens_k, 1)))
    moon = None
    if slot == 'moon_night':
        moon = {'elev': 30.0, 'azim': round((az + 200.0) % 360.0, 1),
                'k': 7500, 'w': 0.35}
    night = el < -2.0
    fire_k = FIRE_K[slot_i] if p['fire'] else None
    if fire_k is not None:
        assert FIRE_MIN_K <= fire_k <= FIRE_MAX_K
    gain = SKY_LEVEL[slot] / SKY_LEVEL[p['sky_ref']]
    light = {
        'sun_k': round(sun_kelvin(el)) if el > 0 else None,
        'sun_w': sun_watts(el),
        'sky_rgb': list(sky_rgb),
        'sky_strength': sky_strength,
        'stars': starry,
        'sky_gain': round(gain, 4),
        'fire_k': fire_k,
        'night_fire': bool(p.get('night_fire')) and night,
        'exposure_target': TARGET[slot],
    }
    if p.get('window'):
        light['window'] = p['window']
    if p.get('night_fire'):
        light['night_fire_at'] = list(p['night_fire']['at'])
        light['night_fire_w'] = p['night_fire']['k_light']
        light['night_fire_h'] = p['night_fire']['h']
    roll = 0.0 if p['horizon'] else roll
    fire_note = ('огонь %d K' % fire_k) if fire_k else 'огня нет, свет — '\
        'экран прибора 6500 K'
    why = '%s; %s; %s.' % (CAM_WHY[slot_i], LIGHT_WHY[slot], fire_note)
    return {
        'v': v,
        'seed': SEED + v,
        'slot': slot,
        'time_of_day': label,
        'solar_time': hhmm(hour),
        'sun_elev': round(el, 1),
        'sun_azim': round(az, 1),
        'moon': moon,
        'cam': {
            'orbit_yaw': round(yaw * span, 1),
            'orbit_pitch': round(pitch * span, 1),
            'dist_k': dist_k,
            'roll': roll,
            'lens_mm': lens,
            'pos': None, 'yaw': None, 'pitch': None,
        },
        'light': light,
        'narration_ru': LINES[iid][slot_i],
        'why': why,
    }


def build():
    out = {
        'episode': 1,
        'doc': 'docs/story/chorus-ep1/INSIGHT_VARIANTS_144_2026-10-03.md',
        'rule': 'Twelve hours of the day for each insight: the same '
                'meaning and the same law (explains), another camera, '
                'another light, another line. Frames are rendered to '
                'build/insight_variants/ and never enter the APK.',
        'seed': SEED,
        'east_convention': 'sun_azim is a compass bearing (0 north, 90 '
                           'east); each place maps it to its world by '
                           'places.<id>.east',
        'places': {k: {'place': p['place'], 'lat': p['lat'],
                       'doy': p['doy'], 'east': p['east'],
                       'kind': p['kind']}
                   for k, p in PLACES.items()},
        'picks': PICKS,
        'notes': NOTES,
        'variants': {},
    }
    for iid in PLACES:
        out['variants'][iid] = [variant(iid, i + 1, i) for i in range(12)]
    return out


def check(data):
    bad = []
    for iid, vs in data['variants'].items():
        if len(vs) != 12:
            bad.append('%s: %d variants' % (iid, len(vs)))
        for v in vs:
            n = len(v['narration_ru'])
            if n > LINE_MAX:
                bad.append('%s v%02d: %d chars' % (iid, v['v'], n))
            if v['light']['fire_k'] is not None and not (
                    FIRE_MIN_K <= v['light']['fire_k'] <= FIRE_MAX_K):
                bad.append('%s v%02d: fire %s K' % (
                    iid, v['v'], v['light']['fire_k']))
        lines = [v['narration_ru'] for v in vs]
        if len(set(lines)) != len(lines):
            bad.append('%s: repeated line' % iid)
    return bad


def merge(data):
    """Write the camera each frame was actually shot from (after the
    renderer's orbit and its pull-in from walls) into the recipe."""
    n = 0
    for iid, vs in data['variants'].items():
        for v in vs:
            f = BUILD / iid / ('v%02d.json' % v['v'])
            if not f.exists():
                continue
            got = json.loads(f.read_text(encoding='utf-8'))
            for k in ('pos', 'yaw', 'pitch', 'roll', 'lens_mm'):
                v['cam'][k] = got['cam'][k]
            v['light']['exposure_ev'] = got.get('exposure_ev')
            v['cam']['pulled_in'] = got['cam'].get('pulled_in', False)
            n += 1
    return n


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--merge', action='store_true')
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args(argv)
    data = build()
    bad = check(data)
    for b in bad:
        print('BAD', b)
    if args.check:
        return 1 if bad else 0
    if bad:
        return 1
    if args.merge:
        print('merged', merge(data), 'frames')
    OUT.write_text(json.dumps(data, ensure_ascii=False, indent=1) + '\n',
                   encoding='utf-8')
    print('wrote', OUT, OUT.stat().st_size, 'bytes')
    return 0


